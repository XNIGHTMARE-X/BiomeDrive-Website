# Cut the wall tiles from the captured frames (cap/<site>-d-N.png at 1440x900, cap/<site>-m-N.png at 390x844).
# Each tile is a different part of a site; no picture is used twice.
# Writes site/img/wall/*.webp and site/img/wall/tiles.js (the list main.js reads).
# usage: python crops.py
import os, json
from PIL import Image
OUT = '../site/img/wall'
os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):  # these are all generated by this script
    if f.endswith('.webp'): os.remove(os.path.join(OUT, f))

# site: [(frame, (x0, y0, x1, y1)) for desktop crops], [phone frames]
SPEC = {
    'arsh': ([('d0', (0, 180, 960, 900)), ('d1', (0, 230, 1100, 900)), ('d2', (900, 0, 1440, 500)), ('d3', (450, 0, 1440, 780)),
              ('d5', (0, 380, 900, 900)), ('d6', (300, 50, 1440, 800)), ('d7', (0, 100, 1440, 760)), ('d8', (0, 150, 1100, 900)),
              ('d9', (30, 80, 490, 560)), ('d10', (0, 230, 1440, 800))],
             ['m3', 'm4']),
    'triptych': ([('d0', (40, 120, 1060, 680)), ('d2', (820, 90, 1240, 870)), ('d3', (760, 120, 1440, 900)), ('d6', (0, 330, 1100, 760)),
                  ('d7', (30, 60, 1430, 620)), ('d8', (600, 200, 1440, 900)), ('d9', (560, 100, 1440, 560)), ('d10', (150, 120, 1290, 820))],
                 ['m1']),
    'jgn': ([('d0', (0, 150, 1200, 720)), ('d2', (140, 250, 1300, 880)), ('d6', (140, 140, 1340, 520)),
             ('d7', (120, 380, 1440, 880)), ('d9', (150, 520, 1290, 840))],
            ['m6']),
    'naheel': ([('d0', (60, 70, 1400, 820)), ('d1', (0, 230, 1440, 860)), ('d3', (90, 200, 1350, 870)),
                ('d4', (90, 280, 1360, 880)), ('d7', (110, 50, 1340, 690)), ('d8', (90, 160, 1350, 890))],
               ['m3']),
}
# One shot per section of a site: a section shown as a desktop crop is not shown again as a phone screen.
# Left out on purpose: frames that show anyone's email or phone number.

tiles = []
for site, (crops, phones) in SPEC.items():
    for frame, box in crops:
        im = Image.open(f'cap/{site}-d-{frame[1:]}.png').convert('RGB').crop(tuple(box))
        w = min(820, im.width)
        im = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
        name = f'{site}-{frame}.webp'
        im.save(f'{OUT}/{name}', quality=80, method=6)
        tiles.append([site, name, round(im.width / im.height, 4), 'c'])
    for frame in phones:
        im = Image.open(f'cap/{site}-m-{frame[1:]}.png').convert('RGB')
        im = im.resize((360, round(im.height * 360 / im.width)), Image.LANCZOS)
        name = f'{site}-{frame}.webp'
        im.save(f'{OUT}/{name}', quality=80, method=6)
        tiles.append([site, name, round(im.width / im.height, 4), 'p'])

# interleave sites so neighbours (dealt round-robin into columns) differ
by = {}
for t in tiles: by.setdefault(t[0], []).append(t)
order = []
while any(by.values()):
    for k in list(by):
        if by[k]: order.append(by[k].pop(0))
with open(f'{OUT}/tiles.js', 'w', encoding='utf-8') as f:
    f.write('/* Wall tiles: [site, file, width/height, "p" phone or "c" crop]. Made by tools/crops.py; every picture is unique. */\n')
    f.write('window.WALL_TILES = ' + json.dumps(order, separators=(',', ':')).replace('],[', '],\n[') + ';\n')
print(len(order), 'tiles')
